#!/usr/bin/env bash
# Runs INSIDE the live root (from customize.sh). Builds the "lacuna" Plymouth theme from the live user's default
# wallpaper and its matugen palette: the dotfiles' boot-theme.sh look (blurred wallpaper, accent ring spinner) plus a
# progress bar for the copy to RAM (fed by the lacuna_progress initcpio hook).
set -euo pipefail
H=/home/amnesia
# palette: rice-theme-sync writes ~/.cache/rice/colors.json (newer dotfiles); older ones had matugen write the bar's
COLORS=$H/.cache/rice/colors.json
[[ -r $COLORS ]] || COLORS=$H/.config/quickshell/bar/colors.json
WALL=$(cat "$H/.cache/rice/current")
T=/usr/share/plymouth/themes/lacuna
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
[[ -r $COLORS && -r $WALL ]] || { echo "plymouth-theme: no palette ($COLORS) or wallpaper ($WALL)" >&2; exit 1; }

col() { python3 -I -c "import json,sys; print(json.load(open(sys.argv[1]))[sys.argv[2]].lstrip('#'))" "$COLORS" "$1"; }
SURFACE=$(col surface); PRIMARY=$(col primary); HIGH=$(col surfaceHigh)

rm -rf "$T"; mkdir -p "$T"
ffmpeg -loglevel error -threads 1 -filter_threads 1 -y -i "$WALL" \
    -vf "scale=1920:1080:force_original_aspect_ratio=increase,crop=1920:1080,gblur=sigma=18,eq=brightness=-0.06:saturation=1.05,format=rgb24" \
    -frames:v 1 "$T/bg.png"
# (the dotfiles' boot-theme.sh dims by 0.22 at 1280x720: on a dark wallpaper that crushes it to black with a few
#  bright streaks, and Plymouth then upscales it; full HD and light dimming keep the picture recognisable)
cat > "$W/track.svg" <<SVG
<svg xmlns="http://www.w3.org/2000/svg" width="200" height="200" viewBox="0 0 200 200">
  <circle cx="100" cy="100" r="46" fill="none" stroke="#$HIGH" stroke-opacity="0.55" stroke-width="7"/>
</svg>
SVG
cat > "$W/arc.svg" <<SVG
<svg xmlns="http://www.w3.org/2000/svg" width="200" height="200" viewBox="0 0 200 200">
  <circle cx="100" cy="100" r="46" fill="none" stroke="#$PRIMARY" stroke-width="7" stroke-linecap="round" stroke-dasharray="110 180"/>
</svg>
SVG
cat > "$W/dot.svg" <<SVG
<svg xmlns="http://www.w3.org/2000/svg" width="18" height="18"><circle cx="9" cy="9" r="9" fill="#$PRIMARY"/></svg>
SVG
cat > "$W/bartrack.svg" <<SVG
<svg xmlns="http://www.w3.org/2000/svg" width="320" height="8"><rect width="320" height="8" rx="4" fill="#$HIGH" fill-opacity="0.75"/></svg>
SVG
cat > "$W/barfill.svg" <<SVG
<svg xmlns="http://www.w3.org/2000/svg" width="320" height="8"><rect width="320" height="8" rx="4" fill="#$PRIMARY"/></svg>
SVG
cat > "$W/note.svg" <<SVG
<svg xmlns="http://www.w3.org/2000/svg" width="640" height="44" viewBox="0 0 640 44">
  <rect x="1" y="1" width="638" height="42" rx="21" fill="#$HIGH" fill-opacity="0.85"/>
  <text x="320" y="28" text-anchor="middle" font-family="JetBrainsMono Nerd Font" font-size="17" fill="#$PRIMARY">Running from RAM: you can remove the USB stick now</text>
</svg>
SVG
for n in track arc dot bartrack barfill note; do rsvg-convert -o "$T/$n.png" "$W/$n.svg"; done
read -r R G B <<<"$(python3 -I -c "import sys; h=sys.argv[1]; print(*(round(int(h[i:i+2],16)/255,3) for i in (0,2,4)))" "$SURFACE")"

cat > "$T/lacuna.script" <<'PLYSCRIPT'
# Lacuna boot screen (generated by lacuna/scripts/plymouth-theme.sh). Look from the dotfiles' boot-theme.sh.
Window.SetBackgroundTopColor(@R@, @G@, @B@);
Window.SetBackgroundBottomColor(@R@, @G@, @B@);

sw = Window.GetWidth();
sh = Window.GetHeight();
cx = Window.GetX() + sw / 2;
cy = Window.GetY() + sh / 2;

bg_img = Image("bg.png");
bg = Sprite(bg_img.Scale(sw, sh));
bg.SetPosition(Window.GetX(), Window.GetY(), -100);

arc_img = Image("arc.png");
track_img = Image("track.png");
dot_img = Image("dot.png");
track = Sprite(track_img);
track.SetPosition(cx - track_img.GetWidth() / 2, cy - track_img.GetHeight() / 2, 1);
arc = Sprite(arc_img);
arc.SetPosition(cx - arc_img.GetWidth() / 2, cy - arc_img.GetHeight() / 2, 2);
dot = Sprite(dot_img);
dot.SetPosition(cx - dot_img.GetWidth() / 2, cy - dot_img.GetHeight() / 2, 3);

# copy-to-RAM progress: a track and a fill under the ring, faded in while "lacuna-progress:<n>" messages arrive
bt_img = Image("bartrack.png");
bf_img = Image("barfill.png");
bar_w = bt_img.GetWidth();
bar_x = cx - bar_w / 2;
bar_y = cy + 110;
bar_track = Sprite(bt_img);
bar_track.SetPosition(bar_x, bar_y, 5);
bar_track.SetOpacity(0);
bar_fill = Sprite();
bar_fill.SetPosition(bar_x, bar_y, 6);
bar_fill.SetOpacity(0);
bar_target = 0;
bar_alpha = 0;
pct = 0;
shown_pct = -1;

# stickless mode: a note once the stick may be pulled ("lacuna-note:stick-free" from the late initcpio hook)
note_img = Image("note.png");
note = Sprite(note_img);
note.SetPosition(cx - note_img.GetWidth() / 2, cy + 150, 7);
note.SetOpacity(0);
note_target = 0;
note_alpha = 0;

angle = 0;
tick = 0;

fun refresh_callback() {
  global.tick = tick + 1;
  global.angle = angle + 0.085;
  rot = arc_img.Rotate(angle);
  arc.SetImage(rot);
  arc.SetPosition(cx - rot.GetWidth() / 2, cy - rot.GetHeight() / 2, 2);
  dot.SetOpacity(0.7 + 0.3 * Math.Sin(tick * 0.06));

  global.bar_alpha = bar_alpha + (bar_target - bar_alpha) * 0.15;
  if (pct != shown_pct) {
    global.shown_pct = pct;
    w = Math.Int(bar_w * pct / 100);
    if (w < 8) { w = 8; }
    bar_fill.SetImage(bf_img.Scale(w, bf_img.GetHeight()));
  }
  bar_track.SetOpacity(bar_alpha);
  bar_fill.SetOpacity(bar_alpha);
  global.note_alpha = note_alpha + (note_target - note_alpha) * 0.12;
  note.SetOpacity(note_alpha);
}
Plymouth.SetRefreshFunction(refresh_callback);

fun message_callback(text) {
  if (text == "lacuna-note:stick-free") {
    global.note_target = 1;
  }
  if (text == "lacuna-progress:done") {
    global.pct = 100;
    global.bar_target = 0;
  } else {
@PROGRESS_CASES@
  }
}
Plymouth.SetDisplayMessageFunction(message_callback);
PLYSCRIPT
sed -i -e "s/@R@/$R/g" -e "s/@G@/$G/g" -e "s/@B@/$B/g" "$T/lacuna.script"
# one literal comparison per percentage: the script language's number-to-string formatting isn't something to rely on
cases=$(for i in $(seq 0 100); do
    printf '    if (text == "lacuna-progress:%d") { global.pct = %d; global.bar_target = 1; }\n' "$i" "$i"; done)
python3 -I - "$T/lacuna.script" "$cases" <<'PY'
import sys
p, cases = sys.argv[1], sys.argv[2]
s = open(p).read()
open(p, 'w').write(s.replace('@PROGRESS_CASES@', cases.rstrip('\n')))
PY

cat > "$T/lacuna.plymouth" <<PLY
[Plymouth Theme]
Name=Lacuna
Description=Lacuna boot screen (wallpaper, spinner, copy-to-RAM progress)
ModuleName=script

[script]
ImageDir=$T
ScriptFile=$T/lacuna.script
PLY
echo "   plymouth theme: $T"
